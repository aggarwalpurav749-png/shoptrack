-- ShopTrack database schema. Safe to run again and again (IF NOT EXISTS everywhere).
-- Phase 1 uses: users, settings, parties, products, product_images, price_history.
-- orders / invoices / payments (Phase 2) and location_pings / visits (Phase 3) are created now
-- so the next phases can be added without changing anything that already exists.

CREATE TABLE IF NOT EXISTS users (
  id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email                TEXT NOT NULL,
  password_hash        TEXT NOT NULL,
  name                 TEXT NOT NULL,
  phone                TEXT,
  role                 TEXT NOT NULL DEFAULT 'AGENT' CHECK (role IN ('ADMIN', 'AGENT')),
  is_active            BOOLEAN NOT NULL DEFAULT TRUE,
  must_change_password BOOLEAN NOT NULL DEFAULT TRUE,
  token_version        INTEGER NOT NULL DEFAULT 0,
  work_start           TEXT,            -- per-agent working hours (Phase 3 tracking), "09:30"
  work_end             TEXT,
  created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS users_email_uq ON users (lower(email));

CREATE TABLE IF NOT EXISTS settings (
  id                  INTEGER PRIMARY KEY CHECK (id = 1),   -- one row only
  shop_name           TEXT NOT NULL DEFAULT 'My Shop',
  logo_url            TEXT,
  logo_public_id      TEXT,
  logo_storage        TEXT,
  gstin               TEXT,
  address             TEXT,
  phone               TEXT,
  email               TEXT,
  bank_name           TEXT,
  account_no          TEXT,
  ifsc                TEXT,
  upi_id              TEXT,
  invoice_prefix      TEXT NOT NULL DEFAULT 'EST',
  next_invoice_no     INTEGER NOT NULL DEFAULT 1,
  work_start          TEXT NOT NULL DEFAULT '09:00',
  work_end            TEXT NOT NULL DEFAULT '18:00',
  default_gst_percent NUMERIC(5,2) NOT NULL DEFAULT 18,
  terms               TEXT,
  updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS parties (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name              TEXT NOT NULL,
  owner_name        TEXT,
  phone             TEXT,
  email             TEXT,
  address           TEXT,
  area              TEXT,
  gstin             TEXT,
  credit_limit      NUMERIC(14,2) NOT NULL DEFAULT 0,
  opening_balance   NUMERIC(14,2) NOT NULL DEFAULT 0,
  current_balance   NUMERIC(14,2) NOT NULL DEFAULT 0,   -- opening balance +/- invoices and payments (Phase 2)
  assigned_agent_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  is_active         BOOLEAN NOT NULL DEFAULT TRUE,
  deleted_at        TIMESTAMPTZ,                         -- soft delete
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS parties_phone_uq ON parties (phone) WHERE deleted_at IS NULL AND phone IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS parties_gstin_uq ON parties (gstin) WHERE deleted_at IS NULL AND gstin IS NOT NULL;
CREATE INDEX IF NOT EXISTS parties_agent_idx ON parties (assigned_agent_id);
CREATE INDEX IF NOT EXISTS parties_area_idx ON parties (area);

CREATE TABLE IF NOT EXISTS products (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name            TEXT NOT NULL,
  sku             TEXT,
  category        TEXT,
  brand           TEXT,
  unit            TEXT NOT NULL DEFAULT 'PCS',
  mrp             NUMERIC(14,2) NOT NULL DEFAULT 0,
  selling_price   NUMERIC(14,2) NOT NULL DEFAULT 0,
  cost_price      NUMERIC(14,2) NOT NULL DEFAULT 0,      -- admin only, never sent to agents
  gst_percent     NUMERIC(5,2) NOT NULL DEFAULT 18,
  hsn             TEXT,
  stock_qty       NUMERIC(14,3) NOT NULL DEFAULT 0,
  low_stock_level NUMERIC(14,3) NOT NULL DEFAULT 10,
  description     TEXT,
  is_archived     BOOLEAN NOT NULL DEFAULT FALSE,
  deleted_at      TIMESTAMPTZ,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS products_sku_uq ON products (lower(sku)) WHERE deleted_at IS NULL AND sku IS NOT NULL;
CREATE INDEX IF NOT EXISTS products_category_idx ON products (category);

CREATE TABLE IF NOT EXISTS product_images (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  url        TEXT NOT NULL,
  public_id  TEXT,                      -- cloudinary public_id, or file name for local storage
  storage    TEXT,                      -- 'cloudinary' | 'local'
  is_primary BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS product_images_product_idx ON product_images (product_id);

CREATE TABLE IF NOT EXISTS price_history (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id      INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  field           TEXT NOT NULL,        -- mrp | selling_price | cost_price
  old_value       NUMERIC(14,2),
  new_value       NUMERIC(14,2),
  changed_by      INTEGER REFERENCES users(id) ON DELETE SET NULL,
  changed_by_name TEXT,
  changed_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS price_history_product_idx ON price_history (product_id, changed_at DESC);

-- ───────────── Phase 2 (orders, invoices, payments) ─────────────
CREATE TABLE IF NOT EXISTS invoices (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_no    TEXT NOT NULL UNIQUE,
  party_id      INTEGER NOT NULL REFERENCES parties(id),
  created_by    INTEGER REFERENCES users(id) ON DELETE SET NULL,
  invoice_date  TIMESTAMPTZ NOT NULL DEFAULT now(),
  due_date      TIMESTAMPTZ,
  subtotal      NUMERIC(14,2) NOT NULL DEFAULT 0,
  discount      NUMERIC(14,2) NOT NULL DEFAULT 0,
  cgst          NUMERIC(14,2) NOT NULL DEFAULT 0,
  sgst          NUMERIC(14,2) NOT NULL DEFAULT 0,
  igst          NUMERIC(14,2) NOT NULL DEFAULT 0,
  round_off     NUMERIC(14,2) NOT NULL DEFAULT 0,
  grand_total   NUMERIC(14,2) NOT NULL DEFAULT 0,
  amount_paid   NUMERIC(14,2) NOT NULL DEFAULT 0,
  status        TEXT NOT NULL DEFAULT 'UNPAID' CHECK (status IN ('UNPAID', 'PARTIAL', 'PAID', 'CANCELLED')),
  notes         TEXT,
  terms         TEXT,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS orders (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_no    TEXT NOT NULL UNIQUE,
  party_id    INTEGER NOT NULL REFERENCES parties(id),
  agent_id    INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_by  INTEGER REFERENCES users(id) ON DELETE SET NULL,
  status      TEXT NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'CONFIRMED', 'PACKED', 'DISPATCHED', 'DELIVERED', 'CANCELLED')),
  notes       TEXT,
  discount    NUMERIC(14,2) NOT NULL DEFAULT 0,
  subtotal    NUMERIC(14,2) NOT NULL DEFAULT 0,
  tax_amount  NUMERIC(14,2) NOT NULL DEFAULT 0,
  grand_total NUMERIC(14,2) NOT NULL DEFAULT 0,
  invoice_id  INTEGER REFERENCES invoices(id) ON DELETE SET NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS orders_party_idx ON orders (party_id);
CREATE INDEX IF NOT EXISTS orders_agent_idx ON orders (agent_id);

CREATE TABLE IF NOT EXISTS order_items (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id    INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  product_id  INTEGER NOT NULL REFERENCES products(id),
  qty         NUMERIC(14,3) NOT NULL,
  rate        NUMERIC(14,2) NOT NULL,
  discount    NUMERIC(14,2) NOT NULL DEFAULT 0,
  gst_percent NUMERIC(5,2) NOT NULL DEFAULT 18,
  line_total  NUMERIC(14,2) NOT NULL
);

CREATE TABLE IF NOT EXISTS payments (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id INTEGER REFERENCES invoices(id) ON DELETE SET NULL,
  party_id   INTEGER NOT NULL REFERENCES parties(id),
  amount     NUMERIC(14,2) NOT NULL,
  method     TEXT NOT NULL CHECK (method IN ('CASH', 'UPI', 'CHEQUE', 'BANK_TRANSFER', 'CREDIT_NOTE')),
  reference  TEXT,
  notes      TEXT,
  paid_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ───────────── Phase 3 (GPS tracking, visits) ─────────────
CREATE TABLE IF NOT EXISTS location_pings (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  lat        DOUBLE PRECISION NOT NULL,
  lng        DOUBLE PRECISION NOT NULL,
  accuracy   DOUBLE PRECISION,
  battery    DOUBLE PRECISION,
  speed      DOUBLE PRECISION,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS location_pings_user_idx ON location_pings (user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS visits (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  party_id     INTEGER NOT NULL REFERENCES parties(id),
  lat          DOUBLE PRECISION,
  lng          DOUBLE PRECISION,
  check_in_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  check_out_at TIMESTAMPTZ,
  notes        TEXT,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ───────────── Added with the order -> invoice flow ─────────────
CREATE SEQUENCE IF NOT EXISTS order_no_seq;

CREATE TABLE IF NOT EXISTS invoice_items (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id  INTEGER NOT NULL REFERENCES invoices(id) ON DELETE CASCADE,
  product_id  INTEGER REFERENCES products(id),
  name        TEXT NOT NULL,          -- copied at invoice time so later product edits never change an old invoice
  hsn         TEXT,
  unit        TEXT,
  qty         NUMERIC(14,3) NOT NULL,
  rate        NUMERIC(14,2) NOT NULL,
  discount    NUMERIC(14,2) NOT NULL DEFAULT 0,
  gst_percent NUMERIC(5,2) NOT NULL DEFAULT 0,
  taxable     NUMERIC(14,2) NOT NULL,
  tax         NUMERIC(14,2) NOT NULL DEFAULT 0,
  line_total  NUMERIC(14,2) NOT NULL
);
CREATE INDEX IF NOT EXISTS invoice_items_invoice_idx ON invoice_items (invoice_id);
CREATE INDEX IF NOT EXISTS order_items_order_idx ON order_items (order_id);
CREATE INDEX IF NOT EXISTS invoices_party_idx ON invoices (party_id);
CREATE INDEX IF NOT EXISTS orders_status_idx ON orders (status, created_at DESC);

