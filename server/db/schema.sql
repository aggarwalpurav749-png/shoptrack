-- ───────────── Offline apps: sync support ─────────────
-- Every UPDATE bumps updated_at, so devices can ask "what changed since my last sync?".
CREATE OR REPLACE FUNCTION touch_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DO $$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY['users', 'settings', 'parties', 'products', 'orders', 'invoices'] LOOP
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'touch_' || t) THEN
      EXECUTE format('CREATE TRIGGER %I BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION touch_updated_at()', 'touch_' || t, t);
    END IF;
  END LOOP;
END $$;

-- changing a product photo must make the product "changed" too
CREATE OR REPLACE FUNCTION touch_product_from_image() RETURNS trigger AS $$
BEGIN
  UPDATE products SET updated_at = now() WHERE id = COALESCE(NEW.product_id, OLD.product_id);
  RETURN NULL;
END;
$$ LANGUAGE plpgsql;
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'touch_product_images') THEN
    CREATE TRIGGER touch_product_images AFTER INSERT OR UPDATE OR DELETE ON product_images FOR EACH ROW EXECUTE FUNCTION touch_product_from_image();
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS parties_updated_idx ON parties (updated_at);
CREATE INDEX IF NOT EXISTS products_updated_idx ON products (updated_at);
CREATE INDEX IF NOT EXISTS orders_updated_idx ON orders (updated_at);
CREATE INDEX IF NOT EXISTS invoices_updated_idx ON invoices (updated_at);

-- every change a device sends is remembered once, so a retry after a bad network never creates it twice
CREATE TABLE IF NOT EXISTS sync_ops (
  op_id      TEXT PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  state      TEXT NOT NULL DEFAULT 'RUNNING' CHECK (state IN ('RUNNING', 'DONE')),
  status     INTEGER,
  response   JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Order / estimate numbers handed to a device in advance, so it can number bills while offline.
CREATE TABLE IF NOT EXISTS number_blocks (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  kind       TEXT NOT NULL CHECK (kind IN ('ORDER', 'INVOICE')),
  from_n     INTEGER NOT NULL,
  to_n       INTEGER NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS number_blocks_user_idx ON number_blocks (user_id, kind);

-- "GPS was switched off" and similar moments, so the owner can see them
CREATE TABLE IF NOT EXISTS agent_events (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  kind       TEXT NOT NULL,
  at         TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS agent_events_uq ON agent_events (user_id, kind, at);

-- pings that arrive late (sent after the agent was offline) must not be saved twice
CREATE UNIQUE INDEX IF NOT EXISTS location_pings_user_time_uq ON location_pings (user_id, created_at);
